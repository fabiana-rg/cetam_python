#Laço de repetição


# renge(): controlando a repetição
for i in range(1, 6):
    print(i)
print("")

# Início, fim e passo
for i in range(2, 11, 2):
    print(i)
print("")

# a variável do 'for'
for contador in range(1, 6):
    print(contador)
print("")

# for com cálculos
for numero in range(1, 6):
    dobro = numero * 2
    print(dobro)
print("")

# for + if
for numero in range(1, 11):
    if numero % 2 == 0:
        print(numero)

